/// Removes a notes-first meeting left untouched (spec F-NM-5). Database only; never touches files.
#[tauri::command]
pub async fn api_discard_empty_meeting(
    state: tauri::State<'_, AppState>,
    meeting_id: String,
    default_title: String,
) -> Result<bool, String> {
    let pool = state.db_manager.pool();
    let discarded = MeetingsRepository::discard_if_empty(pool, &meeting_id, &default_title)
        .await
        .map_err(|e| {
            log_error!("Failed to check meeting {} for discard: {}", meeting_id, e);
            format!("Could not tidy up the meeting: {}", e)
        })?;
    if discarded {
        crate::markdown_export::schedule(pool, &meeting_id, crate::markdown_export::CHANGE_DELAY);
    }
    Ok(discarded)
}

/// Opens the meeting's recording folder in the system file explorer
#[tauri::command]
pub async fn open_meeting_folder<R: Runtime>(
    _app: AppHandle<R>,
    state: tauri::State<'_, AppState>,
    meeting_id: String,
) -> Result<(), String> {
    log_info!("open_meeting_folder called for meeting_id: {}", meeting_id);

    let pool = state.db_manager.pool();

    // Get meeting with folder_path
    let meeting: Option<MeetingModel> = sqlx::query_as(
        "SELECT id, title, created_at, updated_at, folder_path FROM meetings WHERE id = ?",
    )
    .bind(&meeting_id)
    .fetch_optional(pool)
    .await
    .map_err(|e| format!("Database error: {}", e))?;

    match meeting {
        Some(m) => {
            if let Some(folder_path) = m.folder_path {
                log_info!("Opening the recording folder of meeting {}", meeting_id);

                // Verify folder exists
                let path = std::path::Path::new(&folder_path);
                // A directory only: handing a file path to the file manager would launch that file
                if !path.is_dir() {
                    log_warn!("The recording folder of meeting {} does not exist or is not a folder", meeting_id);
                    return Err(format!("Recording folder not found: {}", folder_path));
                }

                // Open folder based on OS
                #[cfg(target_os = "macos")]
                {
                    // net: none: opens a meeting folder in the file manager
                    std::process::Command::new("open")
                        .arg(&folder_path)
                        .spawn()
                        .map_err(|e| format!("Failed to open folder: {}", e))?;
                }

                #[cfg(target_os = "windows")]
                {
                    // net: none: opens a meeting folder in the file manager
                    std::process::Command::new("explorer")
                        .arg(&folder_path)
                        .spawn()
                        .map_err(|e| format!("Failed to open folder: {}", e))?;
                }

                #[cfg(target_os = "linux")]
                {
                    // net: none: opens a meeting folder in the file manager
                    std::process::Command::new("xdg-open")
                        .arg(&folder_path)
                        .spawn()
                        .map_err(|e| format!("Failed to open folder: {}", e))?;
                }

                log_info!("Opened the recording folder of meeting {}", meeting_id);
                Ok(())
            } else {
                log_warn!("Meeting {} has no folder_path set", meeting_id);
                Err("Recording folder path not available for this meeting".to_string())
            }
        }
        None => {
            log_warn!("Meeting not found: {}", meeting_id);
            Err("Meeting not found".to_string())
        }
    }
}

/// Opens a consent guidance link (spec F-CON-4): only hosts on the guidance allowlist.
