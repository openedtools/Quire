#[tauri::command]
pub async fn api_delete_meeting<R: Runtime>(
    _app: AppHandle<R>,
    state: tauri::State<'_, AppState>,
    meeting_id: String,
    auth_token: Option<String>,
) -> Result<serde_json::Value, String> {
    log_info!(
        "api_delete_meeting called for meeting_id(native): {}, auth_token: {}",
        meeting_id,
        auth_token.is_some()
    );

    let pool = state.db_manager.pool();

    // Two phases (spec F-RET-12): the files go first, and the row only when they are gone, so a
    // locked file leaves the meeting listed as deleting instead of an orphaned folder
    match crate::retention::delete_meeting(pool, &meeting_id).await {
        Ok(d) if d.removed => Ok(serde_json::json!({
            "status": "success",
            "message": "Meeting deleted successfully",
            "recording_files_removed": d.files_removed,
            "pending": false
        })),
        Ok(d) if d.files_pending > 0 => Ok(serde_json::json!({
            "status": "pending",
            "message": "Some recording files are in use; the meeting is removed once they are free",
            "recording_files_removed": d.files_removed,
            "pending": true
        })),
        Ok(_) => {
            log_warn!("Meeting not found or already deleted: {}", meeting_id);
            Err(format!("Meeting not found or could not be deleted: {}", meeting_id))
        }
        Err(e) => {
            log_error!("Error deleting meeting {}: {}", meeting_id, e);
            Err(format!("Failed to delete meeting: {}", e))
        }
    }
}

