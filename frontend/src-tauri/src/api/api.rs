#[tauri::command]
pub async fn api_save_model_config<R: Runtime>(
    _app: AppHandle<R>,
    state: tauri::State<'_, AppState>,
    provider: String,
    model: String,
    whisper_model: String,
    api_key: Option<String>,
    ollama_endpoint: Option<String>,
    _auth_token: Option<String>,
    confirm_remote: Option<bool>,
) -> Result<serde_json::Value, String> {
    log_info!(
        "💾 api_save_model_config called (native): provider='{}', model='{}', whisperModel='{}', ollamaEndpoint={:?}",
        &provider,
        &model,
        &whisper_model,
        ollama_endpoint.as_deref().map(crate::cloud::redacted)
    );
    let pool = state.db_manager.pool();

    // A new Ollama address on another computer needs the person's yes first, whichever provider
    // is being saved, since the address is kept for later (F-MOD-7)
    {
        let saved = SettingsRepository::get_model_config(pool).await.ok().flatten().and_then(|s| s.ollama_endpoint);
        let unchanged = saved.as_deref().map(str::trim) == ollama_endpoint.as_deref().map(str::trim);
        if crate::cloud::remote_needs_confirmation(ollama_endpoint.as_deref(), confirm_remote.unwrap_or(false) || unchanged) {
            return Err(crate::cloud::NEEDS_CONFIRMATION.to_string());
        }
    }

    // The key first: if the credential store refuses it, nothing else changes (F-MOD-6).
    // Skip API key saving for custom-openai provider (it uses customOpenAIConfig JSON instead)
    if let Some(key) = api_key {
        if !key.trim().is_empty() && provider != "custom-openai" {
            log_info!("🔑 API key provided, saving...");
            if let Err(e) = SettingsRepository::save_api_key(pool, &provider, &key).await {
                log_error!("❌ Failed to save API key: {}", e);
                return Err(e.to_string());
            }
        }
    }

    if let Err(e) = SettingsRepository::save_model_config(
        pool,
        &provider,
        &model,
        &whisper_model,
        ollama_endpoint.as_deref(),
    )
    .await
    {
        log_error!("❌ Failed to save model config to database: {}", e);
        return Err(e.to_string());
    }

    // Trigger graceful shutdown of built-in AI sidecar if it's running
    // This ensures that if the user switched models/providers, the old one is cleaned up
    // The shutdown happens in the background, so it won't block the UI
    if let Err(e) = crate::summary::summary_engine::client::shutdown_sidecar_gracefully().await {
        log_warn!("Failed to initiate graceful sidecar shutdown: {}", e);
    }

    log_info!("✅ Successfully saved model configuration to database");
    Ok(
        serde_json::json!({ "status": "success", "message": "Model configuration saved successfully" }),
    )
}

/// Whether a key is saved for a summary provider. The key itself never goes to the window.
